// 國中九年級物理計算題 expert-501～570 的答案驗證函式：以公式實際算出正解選項文字。

/** 數字格式化：去掉浮點誤差，最多保留 2 位小數。 */
const n = (x) => String(Math.round(x * 100) / 100);

export default {
  // 路徑長＝各段相加；位移＝東 300 m 減西 100 m。
  'expert-501': () => { const east = 300, west = 100; return `路徑長 ${n(east + west)} m，位移 ${n(east - west)} m 向${east > west ? '東' : '西'}`; },
  // 平均速率＝路徑長 ÷ 時間；繞一圈位移為 0。
  'expert-502': () => { const path = 400, disp = 0, t = 80; return `平均速率 ${n(path / t)} m/s，平均速度 ${n(disp / t)} m/s`; },
  // 144 km ÷ 2 h 換成 m/s。
  'expert-503': () => `${n((144 * 1000) / (2 * 3600))} m/s`,
  // 加速度＝速度變化 ÷ 時間。
  'expert-504': () => `${n((5 - 0) / 5)} m/s²`,
  // a＝F ÷ m。
  'expert-513': () => `${n(6 / 2)} m/s²`,
  // 合力＝推力－摩擦力，a＝合力 ÷ m。
  'expert-514': () => `${n((100 - 40) / 30)} m/s²`,
  // 靜止時合力為 0，靜摩擦力與推力等大反向。
  'expert-518': () => { const push = 20, friction = push; return `${n(friction)} N，方向與推力相反`; },
  // 功＝力 × 距離。
  'expert-521': () => `${n(20 * 3)} J`,
  // 功率＝（物重 × 高度）÷ 時間。
  'expert-522': () => `${n((200 * 2) / 4)} W`,
  // 動能＝½ m v²。
  'expert-524': () => `${n(0.5 * 2 * 3 ** 2)} J`,
  // 動能比＝速率比的平方。
  'expert-525': () => `${n((60 / 30) ** 2)} 倍`,
  // 施力＝抗力 × 抗力臂 ÷ 施力臂。
  'expert-532': () => `${n((600 * 0.2) / 1.2)} N`,
  // 動滑輪：拉力＝物重 ÷ 2，繩端距離＝上升高度 × 2。
  'expert-536': () => { const w = 200, h = 1; return `拉力 ${n(w / 2)} N，繩端拉 ${n(h * 2)} m`; },
  // 硬幣數 × 距離兩邊相等。
  'expert-540': () => `${n((2 * 10) / 5)} 枚`,
  // I＝V ÷ R。
  'expert-544': () => `${n(6 / 2)} A`,
  // 串聯：I＝V ÷（R1＋R2）。
  'expert-545': () => `${n(6 / (2 + 4))} A`,
  // 並聯：各支路 I＝V ÷ R，再相加。
  'expert-546': () => `${n(6 / 6 + 6 / 6)} A`,
  // P＝IV。
  'expert-551': () => `${n(110 * 10)} W`,
  // 度數＝kW × h。
  'expert-552': () => `${n((1000 / 1000) * 3)} 度`,
  // I＝P ÷ V。
  'expert-553': () => `${n(55 / 110)} A`,
  // 能量守恆：得到的能量－輸出電能。
  'expert-567': () => `約 ${n(1000 - 800)} J，主要變成熱能`,
  // 電能＝V × I × t。
  'expert-570': () => `${n(3 * 0.2 * 10)} J`,
};
